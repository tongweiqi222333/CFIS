import {test,expect} from '@playwright/test'
test('会计科目、复式凭证、过账冲销与封账',async({page})=>{
 test.setTimeout(90000)
 await page.goto('/')
 await page.getByLabel('邮箱',{exact:true}).fill('accounting-'+Date.now()+'@example.test')
 await page.getByLabel('密码',{exact:true}).fill('Accounting-E2E!123456')
 await page.getByRole('button',{name:'注册',exact:true}).click()
 await expect(page.getByRole('status').first()).toHaveText('操作成功')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByPlaceholder('企业名称').fill('会计验收企业')
 await page.getByRole('button',{name:'创建',exact:true}).click()
 await page.getByRole('cell',{name:'会计验收企业',exact:true}).click()
 await page.getByRole('link',{name:'会计管理',exact:true}).click()
 const accounting=page.getByRole('region',{name:'会计引擎'})
 await accounting.getByLabel('会计期间代码',{exact:true}).fill('E2E')
 await accounting.getByRole('button',{name:'建立会计期间',exact:true}).click()
 await expect(accounting.getByRole('cell',{name:'E2E',exact:true})).toBeVisible()
 for(const [code,name,kind] of [['1002','验收银行科目','Asset'],['4001','验收资本科目','Equity']]){
 await accounting.getByLabel('科目代码',{exact:true}).fill(code)
 await accounting.getByLabel('科目名称',{exact:true}).fill(name)
 await accounting.getByLabel('科目类别',{exact:true}).selectOption(kind)
 await accounting.getByRole('button',{name:'新增会计科目',exact:true}).click()
 await expect(accounting.getByRole('cell',{name,exact:true})).toBeVisible()
 }
 await accounting.getByLabel('凭证摘要',{exact:true}).fill('浏览器复式记账')
 await accounting.getByLabel('分录科目 0',{exact:true}).selectOption({label:'1002 验收银行科目'})
 await accounting.getByLabel('借方 0',{exact:true}).fill('25.1234')
 await accounting.getByLabel('分录科目 1',{exact:true}).selectOption({label:'4001 验收资本科目'})
 await accounting.getByLabel('贷方 1',{exact:true}).fill('25.1234')
 await accounting.getByRole('button',{name:'保存凭证草稿',exact:true}).click()
 await accounting.getByRole('button',{name:'过账所选凭证',exact:true}).click()
 await expect(accounting.getByRole('cell',{name:'已过账',exact:true})).toBeVisible()
 await accounting.getByLabel('凭证冲销原因',{exact:true}).fill('浏览器验收冲销')
 await accounting.getByRole('button',{name:'冲销所选凭证',exact:true}).click()
 await expect(accounting.getByRole('button',{name:'查看凭证 冲销：浏览器验收冲销',exact:true})).toBeVisible()
 await accounting.getByRole('button',{name:'查询试算平衡',exact:true}).click()
 await expect(accounting.getByText(/借方 50.2468 · 贷方 50.2468 · 差额 0.0000/)).toBeVisible()
 await accounting.getByRole('button',{name:'科目明细 1002',exact:true}).click()
 await expect(accounting.getByText('期初借方净额 0.0000 · 期末借方净额 0.0000',{exact:true})).toBeVisible()
 page.once('dialog',dialog=>dialog.accept())
 await accounting.getByRole('button',{name:'关闭期间 E2E',exact:true}).click()
 await expect(accounting.getByRole('cell',{name:'已关闭',exact:true})).toBeVisible()
 await accounting.screenshot({path:'test-results/accounting-validation.png'})
})
