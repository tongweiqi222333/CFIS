import {test,expect} from '@playwright/test'
test('邀请新用户并由受邀人设置密码进入企业',async({page})=>{
 test.setTimeout(90000)
 await page.goto('/')
 await page.getByLabel('邮箱',{exact:true}).fill('owner-security-'+Date.now()+'@example.test')
 await page.getByLabel('密码',{exact:true}).fill('Security-E2E!123456')
 await page.getByRole('button',{name:'注册',exact:true}).click()
 await expect(page.getByRole('status').first()).toHaveText('操作成功')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await page.getByPlaceholder('企业名称').fill('邀请安全验收企业')
 await page.getByRole('button',{name:'创建',exact:true}).click()
 await page.getByRole('cell',{name:'邀请安全验收企业',exact:true}).click()
 await page.getByRole('link',{name:'企业设置',exact:true}).click()
 await page.getByRole('button',{name:'账户安全与邀请',exact:true}).click()
 const security=page.locator('[aria-label="账户安全与邀请"]')
 const email='invited-security-'+Date.now()+'@example.test'
 await security.getByLabel('安全邮箱',{exact:true}).fill(email)
 await security.getByRole('button',{name:'生成邀请代码',exact:true}).click()
 await expect(security.locator('code')).toBeVisible()
 const token=await security.locator('code').innerText()
 await page.getByRole('button',{name:'退出登录',exact:true}).click()
 await expect(page.getByRole('button',{name:'登录',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'账户安全与邀请',exact:true}).click()
 await security.getByLabel('邀请代码',{exact:true}).fill(token)
 await security.getByLabel('安全新密码',{exact:true}).fill('Invited-E2E!123456')
 await security.getByRole('button',{name:'接受邀请',exact:true}).click()
 await expect(security.getByRole('status')).toHaveText('操作成功')
 await page.getByLabel('邮箱',{exact:true}).fill(email)
 await page.getByLabel('密码',{exact:true}).fill('Invited-E2E!123456')
 await page.getByRole('button',{name:'登录',exact:true}).click()
 await expect(page.getByRole('cell',{name:'邀请安全验收企业',exact:true})).toBeVisible()
})
